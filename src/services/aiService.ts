export interface SemanticChunk {
  text: string;
  label: 'GREEN' | 'BLUE' | 'RED' | 'PINK' | 'NONE';
  ohm: number;
  confidence: number;
  reason: string;
}

export interface OhmAnalysisResult {
  transcriptRaw: string;
  transcriptNormalized: string;
  chunks: SemanticChunk[];
  formula: string;
  totalOhm: number;
}

export async function transcribeAudio(audioBlob: Blob, settings?: AISettings): Promise<string> {
  const base64Audio = await new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onloadend = () => {
      const base64 = (reader.result as string).split(',')[1];
      resolve(base64);
    };
    reader.onerror = reject;
    reader.readAsDataURL(audioBlob);
  });

  const response = await fetch('/api/transcribe', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      audioData: base64Audio,
      mimeType: audioBlob.type || 'audio/webm',
      model: settings?.audioTranscriptModel || 'gemini-2.5-flash',
    }),
  });

  const data = await response.json().catch(() => ({}));
  if (!response.ok) {
    throw new Error(data.error || data.message || `Transcription failed: ${response.status}`);
  }

  return typeof data.transcript === 'string' ? data.transcript.trim() : '';
}

export async function analyzeTranscript(transcript: string, settings?: AISettings, baseOhms?: Record<string, number>): Promise<OhmAnalysisResult> {
  const ohms = settings?.ohmBaseValues || baseOhms || { Green: 3, Blue: 5, Red: 7, Pink: 9 };
  
  const defaultInstructions = `
Bạn là một chuyên gia phân tích ngôn ngữ học. Nhiệm vụ của bạn là bóc tách Transcript thành các "Semantic Chunks" (Cụm nghĩa) và phân loại chúng vào 4 tầng năng lượng (Ohm) sau:

1. GREEN (${ohms.Green} Ohm) - Gap Fillers: Những từ/cụm từ "bôi trơn" hội thoại. Bao gồm quán ngữ, từ nối, từ lặp, hoặc các từ đệm không mang nghĩa chính nhưng giúp câu nói tự nhiên (Ví dụ: "thực ra là", "nói chung là", "à thì", "vậy nên").

2. BLUE (${ohms.Blue} Ohm) - Sentence Frames: Khung câu hoặc mẫu câu giao tiếp nền tảng. Đây là phần "xương sống" của câu, chứa các cấu trúc ngữ pháp dùng để lắp ghép thông tin (Ví dụ: "Tôi định nói với cậu là...", "Nếu... thì...", "Cậu có bao giờ tự hỏi..."). Lưu ý: Chỉ chọn khung câu chưa hoàn chỉnh, không chọn câu trần thuật đã đầy đủ ý nghĩa.

3. RED (${ohms.Red} Ohm) - Idioms & Nuance: Các cụm từ mang tính biểu cảm cao. Gồm thành ngữ, từ láy, ngôn ngữ hình ảnh, hoặc các cách diễn đạt dân dã, ẩn dụ đặc thù của người bản ngữ (Ví dụ: "chuyện nhỏ như con thỏ", "mật ngọt chết ruồi", "tới số rồi").

4. PINK (${ohms.Pink} Ohm) - Key Terms & Concepts: Các từ khóa quan trọng hoặc khái niệm cốt lõi. Gồm danh từ riêng, thuật ngữ chuyên môn, hoặc các đối tượng chính đang được nhắc đến trong đoạn hội thoại (Ví dụ: "trí tuệ nhân tạo", "ví điện tử", "địa lý").`;

  const systemInstructions = settings?.ohmPromptInstructions && settings.ohmPromptInstructions.trim() !== '' 
     ? settings.ohmPromptInstructions 
     : defaultInstructions;

  const prompt = `
${systemInstructions}

CRITICAL RULES FOR CHUNKING:
1. QUALITY OVER QUANTITY: Extract all chunks that truly fit the categories, but ignore common adjectives, basic verbs, and everyday noun phrases.
2. RED IS FOR FIGURATIVE LANGUAGE: Only extract Red if it is a true idiom, metaphor, or vivid colloquial expression. Common praise like "rất tốt", "rất đỉnh", "tuyệt vời" is NOT RED.
3. PINK IS FOR INTERMEDIATE/TECHNICAL VOCABULARY: Only extract Pink if it is a specific topic-related concept, technical term, or academic/intermediate-level vocabulary (e.g., "ứng dụng thực tế", "phát triển bền vững"). Basic nouns like "mèo", "bàn", "nước" are NOT PINK.
4. BLUE MUST BE A FRAME: It must be a reusable structure waiting for content. A complete standalone sentence is rarely BLUE.
5. NO FRAGMENTATION: Don't break phrases that should be together.
6. IGNORE FILLER: If a word adds no energy (like simple "và", "nhưng" in normal use), ignore it unless it acts as a specific discourse marker (GREEN).
7. Extract exact substrings.
8. Brief reason and confidence required.

Rules for Ohm calculation:
- GREEN = ${ohms.Green}, BLUE = ${ohms.Blue}, RED = ${ohms.Red}, PINK = ${ohms.Pink}.
- If multiple chunks have the SAME label, ADD their values.
- If chunks have DIFFERENT labels, MULTIPLY the group sums.

Transcript:
"${transcript}"

Return the result STRICTLY as a JSON object with this structure (example with 2 chunks):
{
  "transcriptRaw": "...",
  "transcriptNormalized": "...",
  "chunks": [
    {
      "text": "chunk 1",
      "label": "BLUE",
      "ohm": ${ohms.Blue},
      "confidence": 0.9,
      "reason": "..."
    },
    {
      "text": "chunk 2",
      "label": "RED",
      "ohm": ${ohms.Red},
      "confidence": 0.8,
      "reason": "..."
    }
  ],
  "formula": "string formula",
  "totalOhm": number
}
`;

  const responseText = await callAI(prompt, settings);
  try {
    const jsonMatch = responseText.match(/```json\n([\s\S]*?)\n```/) || responseText.match(/\{[\s\S]*\}/);
    const jsonString = jsonMatch ? (jsonMatch[1] || jsonMatch[0]) : responseText;
    const result = JSON.parse(jsonString) as OhmAnalysisResult;
    
    // Fallback: If AI parsed successfully but found 0 chunks for a non-empty transcript
    if ((!result.chunks || result.chunks.length === 0) && transcript.trim().length > 5) {
      result.totalOhm = 1;
      result.formula = "1 (Base Energy)";
    }
    
    return result;
  } catch (error) {
    console.error("Failed to parse analysis result:", responseText);
    throw new Error("Failed to parse analysis result from AI.");
  }
}

export async function fetchOpenRouterModels(apiKey: string, endpoint: string = 'https://openrouter.ai/api/v1') {
  if (!apiKey) return [];
  try {
    const response = await fetch(`/api/ai/models?endpoint=${encodeURIComponent(endpoint)}`, {
      method: 'GET',
      headers: {
        'Authorization': `Bearer ${apiKey}`,
      },
    });
    if (!response.ok) throw new Error(`Failed to fetch models: ${response.statusText}`);
    const data = await response.json();
    return data.data || [];
  } catch (error) {
    console.error('Error fetching models:', error);
    throw error;
  }
}

async function callAI(prompt: string, settings?: AISettings): Promise<string> {
  const apiKey = settings?.apiKey;
  const primaryModel = settings?.primaryModel || 'gemini-2.0-flash';
  const fallbackModel = settings?.fallbackModel || 'gemini-1.5-flash';
  const endpoint = settings?.endpoint;
  const modelsToTry = [primaryModel, fallbackModel].filter(Boolean);
  let lastError = null;

  for (const model of modelsToTry) {
    try {
      const headers: Record<string, string> = {
        'Content-Type': 'application/json',
      };
      if (apiKey) {
        headers['Authorization'] = `Bearer ${apiKey}`;
      }

      const response = await fetch('/api/ai/chat', {
        method: 'POST',
        headers,
        body: JSON.stringify({
          endpoint,
          model,
          messages: [{ role: 'user', content: prompt }],
          stream: false,
        }),
      });

      if (!response.ok) {
        const errorData = await response.json().catch(() => ({}));
        let errorMessage = errorData.error?.message || errorData.error || errorData.message;

        if (!errorMessage && errorData.rawResponse) {
          const raw = errorData.rawResponse;
          if (raw.includes('<html') && raw.includes('530')) {
            errorMessage = 'API Error 530: Cloudflare DNS/Origin error. The AI endpoint might be down or misconfigured.';
          } else {
            errorMessage = `API Error ${response.status}: ${raw.substring(0, 100)}...`;
          }
        }

        errorMessage = errorMessage || `API Error: ${response.status}`;
        throw new Error(typeof errorMessage === 'string' ? errorMessage : JSON.stringify(errorMessage));
      }

      const data = await response.json();

      if (data.choices && data.choices.length > 0 && data.choices[0].message) {
        return data.choices[0].message.content;
      }
      if (data.response) {
        return data.response;
      }
      if (data.content && Array.isArray(data.content)) {
        return data.content[0].text;
      }
      if (typeof data.text === 'string') {
        return data.text;
      }
      if (data.rawResponse) {
        if (typeof data.rawResponse === 'string' && data.rawResponse.includes('data: {') && data.rawResponse.includes('"choices"')) {
          let fullContent = '';
          const lines = data.rawResponse.split('\n');
          for (const line of lines) {
            if (line.startsWith('data: ') && line !== 'data: [DONE]') {
              try {
                const chunk = JSON.parse(line.substring(6));
                if (chunk.choices && chunk.choices[0] && chunk.choices[0].delta && chunk.choices[0].delta.content) {
                  fullContent += chunk.choices[0].delta.content;
                }
              } catch (e) {
                // Ignore parse errors for individual lines
              }
            }
          }
          if (fullContent) return fullContent;
        }
        return data.rawResponse;
      }

      throw new Error(`Unexpected API response format: ${JSON.stringify(data).substring(0, 200)}...`);
    } catch (error) {
      console.warn(`Failed with model ${model}:`, error);
      lastError = error;
    }
  }

  throw lastError || new Error('All models failed');
}

function cleanJSON(text: string): string {
  if (!text) return '';
  let cleanText = text.trim();
  
  // Try to extract JSON block if markdown is used
  const jsonMatch = cleanText.match(/```(?:json)?\s*([\s\S]*?)\s*```/);
  if (jsonMatch && jsonMatch[1]) {
    return jsonMatch[1].trim();
  }
  
  // Fallback: try to find the first [ or { and last ] or }
  const firstBrace = cleanText.indexOf('{');
  const lastBrace = cleanText.lastIndexOf('}');
  const firstBracket = cleanText.indexOf('[');
  const lastBracket = cleanText.lastIndexOf(']');
  
  // Determine if it's an array or object based on what comes first
  const hasBracket = firstBracket !== -1 && lastBracket !== -1;
  const hasBrace = firstBrace !== -1 && lastBrace !== -1;

  if (hasBracket && (!hasBrace || firstBracket < firstBrace)) {
    return cleanText.substring(firstBracket, lastBracket + 1);
  } else if (hasBrace) {
    return cleanText.substring(firstBrace, lastBrace + 1);
  }
  
  return cleanText;
}

export async function generateChunk(params: GenerateChunkParams): Promise<GeneratedChunkResponse> {
  const { resources, rTotal, iValue, uTotal, settings, theme, topicLevel, sentenceLength } = params;
  const resourceList = resources.map(r => `${r.name} (${r.color}, ${r.ohm} Ohm${r.hint ? `, Context Hint: ${r.hint}` : ''})`).join(', ');
  
  const currentLen = sentenceLength || 'Medium';
  const constraints = settings?.sentenceConstraints?.[currentLen];
  
  const targetSentences = constraints?.maxSentences || (currentLen === 'Very Short' ? 1 : currentLen === 'Short' ? 2 : currentLen === 'Medium' ? 3 : 5);
  const targetWords = constraints?.maxWords || (currentLen === 'Very Short' ? 15 : currentLen === 'Short' ? 30 : currentLen === 'Medium' ? 60 : 100);
  const minWords = Math.max(5, Math.floor(targetWords * 0.8));

const prompt = `
You are an expert linguist and curriculum designer for an EdTech system called "CHUNKS".
Your task is to generate a bilingual sentence (Vietnamese first, then English) based on a set of input resources and a specific algorithm.

Target Theme/Topic: ${theme === 'INFER_FROM_RESOURCES' ? 'Dynamically infer the most logical and specific theme entirely based on the provided Input Resources. Do NOT use a random theme.' : (theme ? theme : 'Dynamically formulate a random specific theme that completely aligns with the STRICT TL MAPPING RULES below. Do not be generic.')}
Topic Level (TL target): ${topicLevel || 1.0}
--- STRICT TL MAPPING RULES ---
- TL 1.0 - 1.2: Daily life, casual chat, standard routines. (A1-A2 vocabulary)
- TL 1.3 - 1.5: Professional work, academic study, intermediate lifestyle. (B1-B2 vocabulary)
- TL 1.6 - 1.8: Industry-specific discussions, professional meetings, complex operations, business strategies. (B2-C1 vocabulary, natural professional communication)
- TL 1.9 - 2.0: Intellectual discussions, macro-economics, specialized academia. (C1 vocabulary, advanced but plausible in high-level speech/debate)
***ABSOLUTE RULE FOR HIGH TL (>= 1.6):***
1. You are FORBIDDEN from generating casual, daily-life, or basic interpersonal scenarios.
2. The language MUST be formal, academic, or professional.
3. You MUST use sophisticated English vocabulary (B2/C1 level) appropriate for the topic, but it MUST sound natural in real-world professional or intellectual communication. DO NOT use obscure, archaic, or bizarrely low-frequency C2 words that nobody actually uses.
-------------------------------
Desired Sentence Length: ${currentLen}

Algorithm Context:
- U = I * R
- R (Resistance): Base difficulty of resources. Total R = ${rTotal}
- I (Current/MSE): Context/complexity variable. I = ${iValue}
- U (Voltage): Total lesson energy/difficulty. U = ${uTotal}

Input Resources to include in the sentence:
${resourceList}

*** CRITICAL RULES FOR HINTS ***
1. The 'Context Hint' (if provided) is STRICTLY for the English translation ('engSentence').
2. Do NOT insert the English 'Context Hint' directly into the Vietnamese sentence. The Vietnamese sentence MUST ONLY use the natural Vietnamese word.
3. For example, if the Resource is 'Chị Hằng' and the Hint is 'The Moon Lady':
   - Correct vieSentence: "Giảng viên phân tích hình tượng Chị Hằng."
   - Correct engSentence: "The lecturer analyzed the image of The Moon Lady."
   - INCORRECT vieSentence: "Giảng viên phân tích hình tượng The Moon Lady." (DO NOT do this!)

Instructions:
1. ABSOLUTE PRIORITY (Meaning & Logic): The final result MUST be a highly natural, logical, and meaningful sentence/paragraph in real-life context. Do NOT force words together if they create a nonsensical "Frankenstein" sentence. It MUST sound like something a native speaker would actually say in real conversation.
2. Vietnamese First: Start by constructing a logical Vietnamese scenario encompassing the exact meaning of all input resources. Frame the sentence completely in natural Vietnamese. Do NOT insert any English words from the hints into the Vietnamese sentence.
3. English Translation: Translate that Vietnamese concept into a natural-sounding English equivalent. This is where you apply the 'Context Hint' to translate specific terminology. The English version must carry the same semantic integrity and clear intent.
4. Length Calibration: Strictly follow the length constraints for "${currentLen}"! Calculate the word count based on the VIETNAMESE sentence.
   - You MUST generate EXACTLY ${targetSentences} sentence(s) (if "Very Short", exactly 1 small sentence).
   - The total Vietnamese word count MUST be STRICTLY between ${minWords} and ${targetWords} words. Your sentence should ideally be close to ${targetWords} words, but absolutely NOT less than ${minWords}.
5. Theme Adherence: The context MUST strictly revolve around the requested theme. If no theme is provided, dynamically formulate a specific, highly relevant theme that matches the STRICT TL MAPPING RULES. A casual context for a high TL is a critical failure.
6. Energy Level: The structural complexity and vocabulary choice should reflect the U (Voltage) value: ${uTotal}. Higher U means more sophisticated grammar and nuanced meaning.
7. Classification: Assign a specific thematic category. Ensure the category explicitly reflects the TL tier (e.g. "Supply Chain Management" for TL 1.7, not "General Conversation"). It MUST be extremely concise (Maximum 3-5 words), do NOT generate long descriptive phrases.
8. Output Format: Return ONLY JSON. Ensure the final output is meaningful and accurately uses the input parameters.

Output MUST be strictly in the following JSON format:
{
  "engSentence": "...",
  "vieSentence": "...",
  "category": "...",
  "evaluation": "Explanation of how the resources create a meaningful context matching the U: ${uTotal}"
}
`;
  const responseText = await callAI(prompt, settings);
  if (!responseText || !responseText.trim()) {
    throw new Error("AI returned an empty response. This may be due to safety filters blocking the content or an API error.");
  }
  const cleanText = cleanJSON(responseText);
  
  try {
    return JSON.parse(cleanText) as GeneratedChunkResponse & { evaluation?: string };
  } catch (e) {
    console.error("Failed to parse AI response:", cleanText);
    throw new Error(`AI returned invalid JSON format: ${e instanceof Error ? e.message : 'Unknown error'}. Response was: ${cleanText.substring(0, 100)}...`);
  }
}

export async function generateAutoChunks(params: AutoGenerateParams): Promise<AutoGeneratedChunk[]> {
  const { theme, topicLevel, targetU, quantity, sentenceLength, colorPreferences, availableResources, settings } = params;

  const currentLen = sentenceLength || 'Medium';
  const constraints = settings?.sentenceConstraints?.[currentLen];
  const targetSentences = constraints?.maxSentences || (currentLen === 'Very Short' ? 1 : currentLen === 'Short' ? 2 : currentLen === 'Medium' ? 3 : 5);
  const targetWords = constraints?.maxWords || (currentLen === 'Very Short' ? 15 : currentLen === 'Short' ? 30 : currentLen === 'Medium' ? 60 : 100);
  const minWords = Math.max(5, Math.floor(targetWords * 0.8));

  // Pre-filter resources to balance them based on color preferences and target U
  const filteredAvailable = availableResources
    .filter(r => colorPreferences.length === 0 || colorPreferences.includes(r.color))
    .sort((a, b) => Math.abs(a.ohm - (targetU / 3)) - Math.abs(b.ohm - (targetU / 3))) // Heuristic: try to find resources that are roughly 1/3 of target U
    .slice(0, 150);

  const resourceList = filteredAvailable.map(r => ({
    id: r.id,
    name: r.name,
    color: r.color,
    ohm: r.ohm,
    hint: r.hint
  }));

  const formulaType = settings?.formulaType || 'sum';
  const physicsLogic = formulaType === 'sum' 
    ? `- R_total = Sum of all individual resource Ohms (R1 + R2 + R3 + ...). (Example: 5 + 9 + 3 = 17)`
    : `- R_total = Sum(R) for same-color series, then Product of those sums for different colors.`;

const prompt = `
You are a Master Linguistic Architect for the "CHUNKS" EdTech system.
Your mission is to construct ${quantity} high-quality learning chunks.

Theme: ${theme ? theme : 'Determine dynamically based on Topic Level (TL)'}
Topic Level (TL target): ${topicLevel || 1.0}
--- STRICT TL MAPPING RULES ---
- TL 1.0 - 1.2: Daily life, casual chat, standard routines. (A1-A2 vocabulary)
- TL 1.3 - 1.5: Professional work, academic study, intermediate lifestyle. (B1-B2 vocabulary)
- TL 1.6 - 1.8: Industry-specific discussions, professional meetings, complex operations, business strategies. (B2-C1 vocabulary, natural professional communication)
- TL 1.9 - 2.0: Intellectual discussions, macro-economics, specialized academia. (C1 vocabulary, advanced but plausible in high-level speech/debate)
***ABSOLUTE RULE FOR HIGH TL (>= 1.6):***
1. You are FORBIDDEN from generating casual, daily-life, or basic interpersonal scenarios.
2. The language MUST be formal, academic, or professional.
3. You MUST use sophisticated English vocabulary (B2/C1 level) appropriate for the topic, but it MUST sound natural in real-world professional or intellectual communication. DO NOT use obscure, archaic, or bizarrely low-frequency C2 words that nobody actually uses.
-------------------------------
Target Voltage (U): ${targetU}
Sentence Length Constraints ("${currentLen}"):
- STRICTLY EXACTLY ${targetSentences} sentence(s) (if "Very Short", exactly 1 short sentence).
- Total word count MUST be STRICTLY between ${minWords} and ${targetWords + 5} words. Do NOT generate less than ${minWords} words.
Color Preferences: ${colorPreferences.join(', ')}

Available Ingredients (Resources):
${JSON.stringify(resourceList)}

*** CRITICAL RULES FOR HINTS ***
1. The 'hint' (if provided) is STRICTLY for the English translation ('engSentence').
2. Do NOT insert the English 'hint' directly into the Vietnamese sentence. The Vietnamese sentence MUST ONLY use the natural Vietnamese word.
3. For example, if the Resource is 'Chị Hằng' and the Hint is 'The Moon Lady':
   - Correct vieSentence: "Giảng viên phân tích hình tượng Chị Hằng."
   - Correct engSentence: "The lecturer analyzed the image of The Moon Lady."
   - INCORRECT vieSentence: "Giảng viên phân tích hình tượng The Moon Lady." (DO NOT do this!)

Physics Logic:
${physicsLogic}
- U = Complexity Multiplier * R_total.

Construction Flow:
1. Resource Selection: Pick 2-4 resources that mathematically approach the Target U.
2. ABSOLUTE PRIORITY (Meaning & Logic): The generated sentence MUST be highly natural, logical, and meaningful in everyday conversation. Do NOT forcibly combine incompatible phrases just to meet constraints. If the combination sounds awkward, change the context or pick different resources. It must sound like native speech.
3. Vietnamese First Draft: Think deeply and construct a logical, highly natural Vietnamese sentence (or paragraph, reflecting the Sentence Length constraint) encompassing the selected resources. Frame the sentence completely in natural Vietnamese without English hints.
4. English Translation: Translate that Vietnamese concept into natural English. Apply the 'hint' here to translate specific terminology.
5. Evaluation: SELF-CRITIQUE the sentence. Does it make sense? Is the length exactly ${targetSentences} sentences and the Vietnamese word count strictly between ${minWords}-${targetWords} words? If not, REGENERATE before outputting.
6. Final Validation: Ensure all resources used are from the provided list.
7. Classification: Assign a specific thematic "category" string. Ensure the category explicitly reflects the TL tier (e.g. "Supply Chain Management" for TL 1.7). A casual context for a high TL is a critical failure. It MUST be extremely concise (Maximum 3-5 words), do NOT generate long descriptive phrases.

Output strictly as JSON array:
[
  {
    "engSentence": "...",
    "vieSentence": "...",
    "category": "...",
    "resourcesUsed": [...],
    "rTotal": 12.5,
    "iValue": 1.2,
    "uTotal": 15.0,
    "difficultyLabel": "...",
    "evaluation": "Passed: Natural and meaningful."
  }
]
`;

  const responseText = await callAI(prompt, settings);
  if (!responseText || !responseText.trim()) {
    throw new Error("AI returned an empty response. This may be due to safety filters blocking the content or an API error.");
  }
  const cleanText = cleanJSON(responseText);

  try {
    let results = JSON.parse(cleanText);
    
    // If AI returned a single object instead of an array, wrap it
    if (!Array.isArray(results)) {
      if (typeof results === 'object' && results !== null) {
        // Sometimes AI wraps the array in an object like { "chunks": [...] }
        const possibleArray = Object.values(results).find(v => Array.isArray(v));
        if (possibleArray) {
          results = possibleArray;
        } else {
          results = [results];
        }
      } else {
        throw new Error("Parsed JSON is neither an object nor an array.");
      }
    }
    
    // Filter out any that failed internal AI evaluation if the AI was honest
    return (results as (AutoGeneratedChunk & { evaluation?: string })[])
      .filter(r => !r.evaluation || r.evaluation.toLowerCase().includes('pass'));
  } catch (e) {
    console.error("Failed to parse AI response:", cleanText);
    throw new Error(`AI returned invalid JSON format: ${e instanceof Error ? e.message : 'Unknown error'}. Response was: ${cleanText.substring(0, 100)}...`);
  }
}
